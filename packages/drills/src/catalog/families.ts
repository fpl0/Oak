type Lv = Partial<LevelParams> & { categories: string[] } & Record<string, unknown>;
interface FamSpec {
  id: FamilyId;
  title: string;
  kind: FamilyKind;
  alsoKind?: FamilyKind;
  domain: FamilyDomain;
  skills: string;
  lesson: LessonId;
  gates?: Record<number, LessonId | LessonId[]>;
  /** [id, unlockAt, contrastOf?] */
  cats: [string, LessonId, string[]?][];
  /** Shared defaults of every level. */
  base: Omit<LevelParams, "categories"> & Record<string, unknown>;
  /** Each level adds to the defaults; `categories` is cumulative unless `only` is set. */
  levels: (Lv & { only?: boolean })[];
  mastery: number;
  n: number;
  fastRt: number;
  est: number;
  mix: CompositeGroup | null;
  answer: AnswerUiKind;
  mic?: boolean;
  generator: string;
  tips?: Record<string, Md>;
}

function fam(s: FamSpec): FamilyDef {
  const skills = s.skills.split(" ");
  const categories: FamilyCategory[] = s.cats.map(([id, unlockAt, contrastOf]) => ({
    id,
    unlockAt,
    ...(contrastOf ? { contrastOf } : {}),
  }));
  let acc: string[] = [];
  const levels: LevelParams[] = s.levels.map(({ only, ...l }) => {
    acc = only ? [...l.categories] : [...new Set([...acc, ...l.categories])];
    return { ...s.base, ...l, categories: [...acc] } as LevelParams;
  });
  return {
    id: s.id,
    title: s.title,
    kind: s.kind,
    ...(s.alsoKind ? { alsoKind: s.alsoKind } : {}),
    domain: s.domain,
    skills: skills.map((skill, i) => ({ skill: skill as SkillId, w: i === 0 ? 1 : 0.5 })),
    unlock: { lesson: s.lesson, ...(s.gates ? { levelGates: s.gates } : {}) },
    categories,
    levels,
    masteryLevel: s.mastery,
    trialsPerSet: s.n,
    fastRtMs: s.fastRt,
    estTrialSec: s.est,
    retention: s.kind === "concept" ? 0.9 : 0.85,
    mix: s.kind === "concept" ? null : s.mix,
    ...(s.tips ? { confusionTips: s.tips } : {}),
    answer: s.answer,
    ...(s.mic ? { mic: true } : {}),
    generator: s.generator,
  };
}

