function pendingJazz(
  id: FamilyId,
  title: string,
  kind: FamilyKind,
  skills: string,
  lesson: LessonId,
  cats: string[],
  n: number,
  mastery: number,
  answer: AnswerUiKind,
  generator: string,
  alsoKind?: FamilyKind,
  gates?: Record<number, LessonId | LessonId[]>,
  domain: FamilyDomain = "jazz",
): FamilyDef {
  return fam({
    id,
    title,
    kind,
    ...(alsoKind ? { alsoKind } : {}),
    domain,
    skills,
    lesson,
    ...(gates ? { gates } : {}),
    cats: cats.map((c) => [c, lesson]),
    base: base(kind === "concept" ? -1 : 2, KEYS2, "all", [90, 130], "none"),
    levels: cats.map((c) => ({ categories: [c] })),
    mastery: Math.min(mastery, cats.length),
    n,
    fastRt: 4000,
    est: 10,
    mix: kind === "concept" ? null : domain === "sound" ? "harmony" : "harmony",
    answer,
    ...(answer === "mic" ? { mic: true } : {}),
    generator,
  });
}

