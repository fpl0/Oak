// Wave 4 seam (docs/design/wave4.md §3.2): the transcription ladder's grading entry (contracts §2.9, §6.12) and
// the capstone grading mode's length rule (§6.4). A ladder answer is Strudel code graded exactly against the
// hidden reference by the layer's matcher; tempo, meter, key and pickup are given; pass ≥ 0.85. Realism never
// changes a tolerance.
import type {
  ExerciseOf,
  GradeResult,
  KeySpec,
  Matcher,
  MeterId,
  NEvent,
  PickupSpec,
  SwingSpec,
} from "@oak/content-kit";
import { R } from "@oak/content-kit";
import { sectionsFromAst } from "../analyze/sections.ts";
import { periodOf } from "../analyze/tracks.ts";
import type { GradeContext, GradeRequest } from "../types.ts";
import { MODE_LIMITS } from "../types.ts";

export type LadderLevel = 1 | 2 | 3 | 4;
export type RealismLevel = 0 | 1 | 2 | 3 | 4;
/**
 * L3 is staged, bass first (contracts §2.9; curriculum §5 T3): the bass, then the chord qualities, then the
 * Roman numerals, each its own submission, as content-kit `TranscribeStage` stages are.
 */
export type LadderStage = "bass" | "quality" | "rn";

/** Pass threshold of every ladder level (contracts §6.12). */
export const LADDER_PASS = 0.85;
/** Realism rises after this many consecutive ladder sessions at or above `REALISM_UP_AT`, falls after one below `REALISM_DOWN_BELOW`. */
export const REALISM_UP_AFTER = 2;
export const REALISM_UP_AT = 0.9;
export const REALISM_DOWN_BELOW = 0.6;

/**
 * The matcher of each level: L1 drum loops by onsets per drum role (onset F1), L2 bass lines and L4 melodies by
 * the melody matcher (octave-free: the octave is given away by A/B), L3 bass first, then the chords by Roman
 * numeral on the triad core. Owner: grader; these are the Foundation defaults, tuned against generated items.
 */
export const LADDER_MATCHERS: {
  readonly 1: Matcher;
  readonly 2: Matcher;
  readonly 3: Readonly<Record<LadderStage, Matcher>>;
  readonly 4: Matcher;
} = {
  // Onset F1 per drum role, every role weighing the same: a part left out fails (contracts §2.9 "onset F1").
  1: {
    m: "rhythm",
    tol: [1, 32],
    durations: false,
    perRole: true,
    displacementCredit: 0.5,
    roleWeight: "equal",
  },
  2: { m: "melody", pitch: "octave-free", wPitch: 0.6, wRhythm: 0.4, rhythmTol: [1, 32], track: "@bass" },
  3: {
    bass: {
      m: "melody",
      pitch: "octave-free",
      wPitch: 0.7,
      wRhythm: 0.3,
      rhythmTol: [1, 16],
      track: "@bass",
    },
    quality: {
      m: "harmony",
      level: "quality",
      qualityDepth: "triad",
      inversion: false,
      harmonicRhythm: "given",
    },
    rn: { m: "harmony", level: "rn", qualityDepth: "triad", inversion: false, harmonicRhythm: "given" },
  },
  4: { m: "melody", pitch: "octave-free", wPitch: 0.6, wRhythm: 0.4, rhythmTol: [1, 32], track: "@melody" },
};

/** The matcher for a level (and an L3 stage, default `bass`). */
export function ladderMatcher(level: LadderLevel, stage?: LadderStage): Matcher {
  return level === 3 ? LADDER_MATCHERS[3][stage ?? "bass"] : LADDER_MATCHERS[level];
}

/** One generated ladder item as the grader needs it (the hidden code stays on the server). */
export interface LadderItemSpec {
  /** Stable ID of the item (`lad.<level>.<seed>`), used as the exercise ID. */
  itemId: string;
  level: LadderLevel;
  stage?: LadderStage;
  /** The hidden reference code (generated by `@oak/drills` `generateLadderPiece`). */
  reference: string;
  bars: number;
  key: KeySpec;
  meter: MeterId;
  bpm: number;
  pickup?: PickupSpec;
  swing?: SwingSpec;
}

const LAYER = { 1: "drums", 2: "bass", 3: "bass", 4: "melody" } as const;

/** The ladder item as a `transcribe-step` exercise, graded by the normal pipeline. */
export function ladderExercise(item: LadderItemSpec): ExerciseOf<"transcribe-step"> {
  return {
    kind: "transcribe-step",
    id: item.stage ? `${item.itemId}.${item.stage}` : item.itemId,
    version: 1,
    prompt: "",
    skills: [],
    role: "practice",
    hints: null,
    tests: [],
    key: item.key,
    meter: item.meter,
    bpm: item.bpm,
    ...(item.pickup ? { pickup: item.pickup } : {}),
    ...(item.swing ? { swing: item.swing } : {}),
    pass: LADDER_PASS,
    projectId: item.itemId,
    ladder: item.level,
    // The stimulus is played by the pattern source, never shown (contracts §6.12).
    stimulus: { src: "code", code: item.reference, bars: item.bars, loop: true, showCode: false },
    layer:
      item.level === 3 && item.stage !== undefined && item.stage !== "bass" ? "chords" : LAYER[item.level],
    bars: [1, item.bars],
    grading: {
      mode: "auto",
      reference: { solutions: [item.reference], bars: item.bars },
      matcher: ladderMatcher(item.level, item.stage),
    },
    studio: { minRate: 0.25, transposeSemis: true, overlay: true },
  };
}

export interface LadderGradeRequest {
  item: LadderItemSpec;
  /** The learner's code, as typed. */
  code: string;
  /** Grading context minus what the item fixes (mode, key, meter, bpm, pickup, swing). */
  ctx: Omit<GradeContext, "mode" | "key" | "meter" | "bpm" | "pickup" | "swing" | "exerciseGlobalId">;
}

/** The `GradeRequest` a ladder submission becomes (mode `lesson`, contracts §6.4). */
export function ladderGradeRequest(req: LadderGradeRequest): GradeRequest {
  const ex = ladderExercise(req.item);
  return {
    exercise: ex,
    response: { code: req.code },
    ctx: {
      ...req.ctx,
      exerciseGlobalId: `ladder/${ex.id}`,
      mode: "lesson",
      key: req.item.key,
      meter: req.item.meter,
      bpm: req.item.bpm,
      ...(req.item.pickup ? { pickup: req.item.pickup } : {}),
      ...(req.item.swing ? { swing: req.item.swing } : {}),
    },
  };
}

/** A graded pass: status pass at the ladder threshold, not revealed (the flag ladder milestones count). */
export function ladderGradedPass(result: GradeResult): boolean {
  return result.status === "pass" && result.score >= LADDER_PASS && !result.assist.revealed;
}

/** One finished ladder session, oldest first, for the realism rule. */
export interface LadderSessionScore {
  level: LadderLevel;
  realism: RealismLevel;
  /** Best score of the session's graded submissions (0 to 1). */
  score: number;
}

/**
 * The realism rule of contracts §6.12: up one step after `REALISM_UP_AFTER` consecutive sessions at the
 * current level and realism scoring ≥ `REALISM_UP_AT`; down one after a single session below
 * `REALISM_DOWN_BELOW`; R0 to R4. Level changes are not decided here (wave4.md §5.4: the learner moves up a
 * level when the server offers it).
 */
export function nextRealism(history: readonly LadderSessionScore[], current: RealismLevel): RealismLevel {
  const last = history[history.length - 1];
  if (!last) return current;
  if (last.score < REALISM_DOWN_BELOW) return Math.max(0, current - 1) as RealismLevel;
  const run = history.slice(-REALISM_UP_AFTER);
  const up =
    run.length === REALISM_UP_AFTER &&
    run.every((s) => s.score >= REALISM_UP_AT && s.realism === current && s.level === last.level);
  return up ? (Math.min(4, current + 1) as RealismLevel) : current;
}

/** The piece length the capstone mode grades (contracts §6.4): the `arrange()` sum, else the period, ≤ 128. */
export interface CapstoneLength {
  /** Bars of the piece from the AST (may exceed 128). */
  totalBars: number;
  /** Bars actually queried: `min(totalBars, 128)`. */
  queriedBars: number;
  /** `totalBars / cps`: computed, never played. */
  durationSec: number;
  /** True when the piece is longer than the cap (`eval.truncated`). */
  truncated: boolean;
}

export function capstoneLength(code: string, events: readonly NEvent[], cps: number): CapstoneLength {
  const cap = MODE_LIMITS.capstone.maxBars;
  const ast = sectionsFromAst(code);
  const fromAst = ast && "totalBars" in ast ? ast.totalBars : null;
  const last = events.reduce((m, e) => Math.max(m, R.floor(e.onset) + 1), 0);
  const totalBars = fromAst ?? Math.max(1, periodOf(events, Math.max(1, Math.min(cap, last || 1))));
  return {
    totalBars,
    queriedBars: Math.min(totalBars, cap),
    durationSec: cps > 0 ? totalBars / cps : 0,
    truncated: totalBars > cap,
  };
}
