import { GraderHost, type HostMode } from "../host.ts";
const mode = (process.argv[2] ?? "worker") as HostMode;
const t0 = performance.now();
const host = new GraderHost({ mode });
const ready = await host.ready();
const cold = performance.now() - t0;
const t1 = performance.now();
const r = await host.analyze('drums: s("bd*4")\nmel: n("0 2 4").scale("C4:major")', { bars: 2 });
console.log(`${mode} cold=${cold.toFixed(1)}ms initInRealm=${ready.initMs.toFixed(1)}ms firstAnalyze=${(performance.now() - t1).toFixed(1)}ms ok=${r.ok}`);
await host.dispose();
