import { GraderHost, type HostMode } from "../host.ts";
const mode = (process.argv[2] ?? "worker") as HostMode;
const host = new GraderHost({ mode, timeoutMs: 250 });
await host.ready();
const rss = () => (process.memoryUsage().rss / 1e6).toFixed(0);
console.log(mode, "rss before MB", rss());
const t = performance.now();
const r = await host.analyze('const a = []\nwhile (true) a.push(new Array(1e5).fill(1))\ns("bd")', {});
console.log("memory bomb ->", JSON.stringify(r.ok ? "OK?!" : r.error.kind), (performance.now() - t).toFixed(0), "ms; parent rss right after kill MB", rss());
const ok = await host.analyze('s("bd")', {});
Bun.gc(true); await new Promise((r) => setTimeout(r, 500));
console.log("next ok:", ok.ok, "parent rss after gc MB", rss(), "stats", JSON.stringify({ kills: host.stats.kills, crashes: host.stats.crashes }));
const r2 = await host.analyze("let s = 'x'\nwhile (true) s += s\ns('bd')", { timeoutMs: 1500 });
console.log("string doubling ->", JSON.stringify(r2.ok ? "OK?!" : r2.error));
const r3 = await host.analyze("const f = () => f()\nf()\ns('bd')", { timeoutMs: 1500 });
console.log("infinite recursion ->", JSON.stringify(r3.ok ? "OK?!" : r3.error));
await host.dispose();
