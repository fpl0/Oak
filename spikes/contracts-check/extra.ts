import { run, out, midi, nm, show, init } from "./h.ts";
import * as core from "@strudel/core";
await init();
const P = (core as any).Pattern.prototype;
out("ribbon:", typeof P.ribbon, "rib:", typeof P.rib, "compress:", typeof P.compress, "hush:", typeof P.hush);
const T = async (label: string, code: string, from = 0, to = 1, f: (r: any) => string = (r) => show(r.ev)) => {
  const r = await run(code, from, to);
  out(`## ${label}\n   ${code.replace(/\n/g, " ⏎ ")}\n   => ${r.err ? "ERROR: " + r.err : f(r)}${r.logs.length ? "\n   logs: " + JSON.stringify(r.logs.map((l: string) => l.replace(/%c|background-color.*$/g, "").trim())) : ""}`);
};
const V = (r: any) => r.ev.map((e: any) => `${e.b}:${nm(midi(e.v)!)}`).join(" ");
await T("add(n(3))", `n("[0,2,4]").add(n(3)).scale("C4:major")`, 0, 1, V);
await T("add(3) number", `n("[0,2,4]").add(3).scale("C4:major")`, 0, 1, V);
await T("ribbon(2,2)", `n("<0 1 2 3 4 5>").scale("C4:major").ribbon(2, 2)`, 0, 4, V);
await T("root:c3 vs root:g2 on F and A", `chord("<F A Bb D>").mode("root:g2").voicing()`, 0, 4, V);
await T("root:c3", `chord("<F A Bb D C>").mode("root:c3").voicing()`, 0, 5, V);
await T("neo-soul chords by symbol", `chord("<C^7 Am7 Dm7 G7>").voicing()`, 0, 4, V);
await T("Caug default vs triads", `chord("<Caug Caug>").dict("<ireal triads>").voicing()`, 0, 2, V);
await T("dict pattern in chain default", `chord("<C G7>").voicing()`, 0, 2, V);
await T("I V6 vi with bass track", `chords: chord("<C G Am>").dict("triads").voicing()\nbass: note("<c2 b1 a1>")`, 0, 3, (r) => show(r.ev));
await T("2/4 swing hh*4", `s("hh*4").swingBy(1/3, 2)`, 0, 1, (r) => r.ev.map((e: any) => e.b).join(" "));
await T("hh*12 16th swing in 3/4", `s("hh*12").swingBy(1/3, 6)`, 0, 1, (r) => r.ev.map((e: any) => e.b).join(" "));
await T("clave rumba 3-2", `s("<[rim ~ ~ rim ~ ~ ~ rim] [~ ~ rim ~ rim ~ ~ ~]>")`, 0, 2, (r) => r.ev.map((e: any) => e.b).join(" "));
await T("3:2 polyrhythm", `a: s("cb*3")\nb: s("rim*2")`, 0, 1, (r) => show(r.ev));
await T("off with n arithmetic", `n("0 2").off(1/8, x => x.add(n(2))).scale("C4:major")`, 0, 1, (r) => show(r.ev));
await T("late pattern decimals", `s("sd*2").late("<0 .02>")`, 0, 2, (r) => r.ev.map((e: any) => e.bf.toFixed(3)).join(" "));
await T("mini sharp chord inside <>", `chord("<F#m7 Bb^7 Eb7#9 C#o7>").voicing()`, 0, 4, V);
await T("setcpm(23) vs 92/4", `setcpm(23)\ns("bd")`, 0, 1, (r) => String(r.cps));
await T("silence in arrange w/ label", `const melVerse = n("0 1").scale("C4:major")\nmel: arrange([2, silence], [2, melVerse])`, 0, 4, V);
await T("x*4 struct on voicing keep chord per bar", `chord("<C F>").dict("triads").voicing().struct("~ x ~ x")`, 0, 2, (r) => r.ev.map((e: any) => `${e.b}:${nm(midi(e.v)!)}`).join(" "));
