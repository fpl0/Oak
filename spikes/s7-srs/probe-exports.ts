import * as F from 'ts-fsrs';
console.log('bun', Bun.version);
console.log('exports:', Object.keys(F).sort().join(', '));
console.log('FSRSVersion:', F.FSRSVersion);
const p = F.DefaultScheduler();
console.log('DefaultScheduler() returns Promise:', p instanceof Promise);
const s = await p;
console.log('scheduler keys:', Object.keys(s), Object.getOwnPropertyNames(Object.getPrototypeOf(s)));
console.log('model name:', s.definition.model.name, '| model keys:', Object.keys(s.model));
console.log('config:', JSON.stringify(s.config));
console.log('Rating:', F.Rating, 'State:', F.State);
const now = new Date('2026-01-01T00:00:00.000Z');
const card = s.newCard({ now });
console.log('newCard:', card);
for (const it of s.preview({ card, now })) console.log('preview', it.grade, JSON.stringify(it.card));
const r = s.review({ card, grade: F.Rating.Good, now });
console.log('review card:', r.card);
console.log('review revlog:', r.revlog);
console.log('input mutated?', JSON.stringify(card) !== JSON.stringify(s.newCard({ now })));
